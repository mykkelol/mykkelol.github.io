let currentLang = "en";

function setLanguage(lang) {
  const dict = translations[lang];
  if (!dict) return;

  currentLang = lang;
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) {
      if (el.hasAttribute("data-i18n-html")) {
        el.innerHTML = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("is-active", btn.dataset.lang === lang);
  });

  try {
    localStorage.setItem("rf-lang", lang);
  } catch (e) {
    /* ignore storage errors */
  }
}

document.querySelectorAll(".lang-btn").forEach((btn) => {
  btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
});

let saved = "en";
try {
  saved = localStorage.getItem("rf-lang") || "en";
} catch (e) {
  /* ignore storage errors */
}
setLanguage(saved);

/* ---------- Contact modal ---------- */
const modal = document.getElementById("contactModal");
const openBtn = document.getElementById("contactOpen");
const closeBtn = document.getElementById("modalClose");
const cancelBtn = document.getElementById("modalCancel");
const form = document.getElementById("contactForm");
const formError = document.getElementById("formError");
const formSuccess = document.getElementById("formSuccess");
const successClose = document.getElementById("successClose");

function openModal() {
  modal.classList.add("is-open");
  modal.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";
  resetForm();
  const first = document.getElementById("cf-first");
  if (first) first.focus();
}

function closeModal() {
  modal.classList.remove("is-open");
  modal.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
}

function resetForm() {
  form.reset();
  form.hidden = false;
  formSuccess.hidden = true;
  formError.hidden = true;
}

function showError(key) {
  formError.textContent = translations[currentLang][key] || "";
  formError.hidden = false;
}

if (openBtn) openBtn.addEventListener("click", openModal);
if (closeBtn) closeBtn.addEventListener("click", closeModal);
if (cancelBtn) cancelBtn.addEventListener("click", closeModal);
if (successClose) successClose.addEventListener("click", closeModal);

if (modal) {
  modal.addEventListener("click", (e) => {
    if (e.target === modal) closeModal();
  });
}

document.addEventListener("keydown", (e) => {
  if (e.key === "Escape" && modal.classList.contains("is-open")) closeModal();
});

if (form) {
  form.addEventListener("submit", (e) => {
    e.preventDefault();
    formError.hidden = true;

    const data = new FormData(form);
    const firstName = (data.get("firstName") || "").toString().trim();
    const lastName = (data.get("lastName") || "").toString().trim();
    const email = (data.get("email") || "").toString().trim();
    const phone = (data.get("phone") || "").toString().trim();
    const services = data.getAll("services");

    if (!firstName || !lastName || !email || !phone) {
      showError("form_err_required");
      return;
    }
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
      showError("form_err_email");
      return;
    }
    if (services.length === 0) {
      showError("form_err_services");
      return;
    }

    // No backend yet — log the submission and show a confirmation.
    console.log("Contact form submission:", {
      firstName,
      lastName,
      email,
      phone,
      services,
      details: (data.get("details") || "").toString().trim(),
    });

    form.hidden = true;
    formSuccess.hidden = false;
  });
}
